#!/usr/bin/env python3
"""Emits the committed SEP-0051 conformance corpus as a Dart source constant.

The corpus is a JSON document, but the suite that drives it has to run on every
platform this SDK ships to, and the web platform has no file to read at test
time. So the corpus is emitted as source and compiled in.

This reads only committed artefacts. It never invokes the reference CLI, so it
runs in a per-PR job that checks the committed corpus without building the
reference.

Usage:
    python3 emit_dart_corpus.py [--corpus PATH] [--output PATH]

Exit codes:
    0  the Dart source was written
    2  the committed corpus is missing or malformed
"""

import argparse
import json
import os
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.abspath(os.path.join(SCRIPT_DIR, "..", ".."))
DEFAULT_CORPUS = os.path.join(SCRIPT_DIR, "corpus.json")
DEFAULT_OUTPUT = os.path.join(REPO_ROOT, "test", "unit", "sep", "sep51_corpus_data.dart")

HEADER = """// AUTO-GENERATED - DO NOT EDIT
// Generated by tools/sep-51-corpus/emit_dart_corpus.py

/// One entry of the SEP-0051 conformance corpus.
class Sep51CorpusEntry {
  const Sep51CorpusEntry({
    required this.type, // the .x type name, e.g. 'ScAddress'
    required this.dartType, // the SDK class name, e.g. 'XdrSCAddress'
    required this.xdr, // base64 XDR
    required this.json, // the JSON text this SDK must emit
    required this.oracle, // 'reference' or 'incomparable'
    this.oracleJson, // the reference's text, when incomparable
    this.reason, // why it is incomparable
    this.note, // the seed's description
  });

  final String type;
  final String dartType;
  final String xdr;
  final String json;
  final String oracle;
  final String? oracleJson;
  final String? reason;
  final String? note;
}
"""

# Order is the corpus document's own; the Dart entry field order follows the
# constructor above so a reader can put the two side by side.
ENTRY_FIELDS = (
    ("type", "type", False),
    ("dart_type", "dartType", False),
    ("xdr", "xdr", False),
    ("json", "json", False),
    ("oracle", "oracle", False),
    ("oracle_json", "oracleJson", True),
    ("reason", "reason", True),
    ("note", "note", True),
)


class PrerequisiteError(Exception):
    """The committed corpus is absent or malformed."""


def dart_string(value):
    """A single-quoted Dart string literal.

    Escapes the three characters that change meaning inside one -- backslash,
    the quote and the interpolation sigil -- and any character outside
    printable ASCII, which the corpus does not currently carry but which a
    future seed could introduce through a rendering this emitter must not
    corrupt.
    """
    out = ["'"]
    for character in value:
        if character in ("\\", "'", "$"):
            out.append("\\" + character)
        elif " " <= character <= "~":
            out.append(character)
        else:
            out.append("\\u{%x}" % ord(character))
    out.append("'")
    return "".join(out)


def metadata_string(value):
    """Flattens one metadata value to text; the Dart map is Map<String, String>."""
    if isinstance(value, list):
        return ", ".join(str(item) for item in value)
    if isinstance(value, bool):
        return "true" if value else "false"
    return str(value)


def read_corpus(path):
    try:
        with open(path) as handle:
            document = json.load(handle)
    except FileNotFoundError:
        raise PrerequisiteError(
            "the committed corpus is not at %s. Generate it with: "
            "python3 tools/sep-51-corpus/generate_corpus.py" % path)
    except json.JSONDecodeError as error:
        raise PrerequisiteError("%s is not valid JSON: %s" % (path, error))
    for key in ("metadata", "entries"):
        if key not in document:
            raise PrerequisiteError("%s has no '%s' section" % (path, key))
    if not document["entries"]:
        raise PrerequisiteError("%s carries no entries" % path)
    for entry in document["entries"]:
        for key, _, optional in ENTRY_FIELDS:
            if not optional and key not in entry:
                raise PrerequisiteError(
                    "%s has an entry without '%s': %r" % (path, key, entry))
    return document


LINE_LENGTH = 80


def named_argument(lines, indent, name, literal):
    """Appends `name: literal,` the way `dart format` lays it out.

    The formatter moves a value onto its own line, indented four further
    columns, when the single-line form runs past the page width, and it never
    splits a string literal. Emitting that shape here rather than relying on a
    later format pass keeps the emission one deterministic artefact: a drift
    guard that regenerates and diffs then answers whether the emission changed,
    not whether a formatter happened to run over it.
    """
    single = "%s%s: %s," % (" " * indent, name, literal)
    if len(single) <= LINE_LENGTH:
        lines.append(single)
        return
    lines.append("%s%s:" % (" " * indent, name))
    lines.append("%s%s," % (" " * (indent + 4), literal))


def render(document):
    lines = HEADER.splitlines()
    lines.append("")
    lines.append("/// Provenance of the corpus: the reference build that produced it and")
    lines.append("/// the XDR revision this SDK generates from.")
    lines.append("const Map<String, String> sep51CorpusMetadata = <String, String>{")
    for key, value in document["metadata"].items():
        named_argument(lines, 2, dart_string(key),
                       dart_string(metadata_string(value)))
    lines.append("};")
    lines.append("")
    lines.append("/// The SEP-0051 conformance corpus, in the order the corpus document")
    lines.append("/// records it.")
    lines.append("const List<Sep51CorpusEntry> sep51Corpus = <Sep51CorpusEntry>[")
    for entry in document["entries"]:
        lines.append("  Sep51CorpusEntry(")
        for key, dart_name, optional in ENTRY_FIELDS:
            if optional and entry.get(key) is None:
                continue
            named_argument(lines, 4, dart_name, dart_string(entry[key]))
        lines.append("  ),")
    lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--corpus", default=DEFAULT_CORPUS,
                        help="the committed corpus (default: %(default)s)")
    parser.add_argument("--output", default=DEFAULT_OUTPUT,
                        help="where to write the Dart source (default: %(default)s)")
    args = parser.parse_args()

    try:
        document = read_corpus(args.corpus)
    except PrerequisiteError as error:
        print("emit_dart_corpus.py: %s" % error, file=sys.stderr)
        return 2

    source = render(document)
    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, "w") as handle:
        handle.write(source)

    print("Wrote %s" % args.output)
    print("  entries: %d" % len(document["entries"]))
    print("  bytes:   %d" % len(source.encode("utf-8")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
