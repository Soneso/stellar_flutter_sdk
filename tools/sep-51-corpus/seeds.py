"""Hand-authored seeds for the SEP-0051 (XDR-JSON) conformance corpus.

Each seed is a dict:

  type        Reference CLI type name (ScVal), the spelling `stellar-xdr` uses.
  dart_type   SDK class name (XdrSCVal). Resolved from
              ../sep-51-oracle/type_map.json, which is keyed on the .x
              identifier because the SDK's NAME_OVERRIDES is many-to-one.
  json        The value written in the reference's own XDR-JSON form. The
              corpus generator encodes it with the reference CLI, so a document
              that is not valid XDR-JSON for that type fails the build.
  note        One sentence naming the shape the seed pins.
  oracle      Optional. "incomparable" marks a rendering where the SDK follows
              SEP-0051 and the reference does not; such a seed also carries
              spec_form and spec_form_paths.
  spec_form   Optional. Names the transformation the generator applies to the
              reference's output to derive what the SDK must emit:
              "integer_string" or "opaque_hex".
  spec_form_paths
              Required on every incomparable seed, including one carrying no
              transform, where it is the empty list. Lists the exact locations
              the transformation is expected to rewrite: dotted object keys,
              "[n]" for an array index, and "" for the whole value. The
              generator records what it actually rewrote and fails when the two
              sets differ in either direction, so a value-addressed transform
              can neither miss a location nor reach one it was not meant to.
  reason      Required on an incomparable seed carrying no spec_form, where
              there is no transformation to take the explanation from. It
              records why the reference's output is not what the SDK emits, and
              is written into the entry exactly as a transform's own reason is.

Seeds cover the renderings that are not mechanical: every arm of the unions
whose JSON form is a strkey or a bare name, the integer types rendered as
strings, the SEP-0051 escape ladder over bytes-typed and string-typed fields,
empty and populated variable-length data, optionals in both states, and the
name rules that a pin bump could disturb.

Every seed names a type the SDK exposes as a class carrying the four SEP-0051
members. Where the .x declares a typedef the SDK collapses into its container
-- AssetCode4, AssetCode12, PoolID, SCVec, SCMap, SCString, SCSymbol -- the
rendering is pinned at the containing type instead, which is the only site the
SDK has for it.

A SignerKeyEd25519SignedPayload with a zero-length payload is deliberately
absent: the reference decodes it to a strkey it then refuses to encode, and the
SDK refuses it in both directions, so no JSON text exists for the corpus to
pin. The generator asserts the reference still behaves that way and records the
exclusion in the corpus metadata; the input itself is pinned by a hand-written
negative test.

A document carrying $schema is likewise absent. SEP-0051 requires objects to
accept the property; the reference rejects it outright, and the SDK strips it
and never emits it, so no emitted text differs and there is nothing for an
entry to pin. The generator asserts the reference still rejects it and records
that exclusion in the metadata too.
"""

