def _seed(type_name, dart_type, json_value, note, oracle=None, spec_form=None,
          spec_form_paths=None, reason=None):
    seed = {
        "type": type_name,
        "dart_type": dart_type,
        "json": json_value,
        "note": note,
    }
    if oracle is not None:
        seed["oracle"] = oracle
    if spec_form is not None:
        seed["spec_form"] = spec_form
    if spec_form_paths is not None:
        seed["spec_form_paths"] = list(spec_form_paths)
    if reason is not None:
        seed["reason"] = reason
    return seed


